-- Cards put up for sale on eBay, and what became of them: a draft while the
-- listing is being written, listed once it is up, then sold or ended unsold.
-- Mirrors Database.Schema.

CREATE TABLE listings (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    card_id        TEXT COLLATE "C" NOT NULL,
    title          TEXT NOT NULL,
    description    TEXT NOT NULL DEFAULT '',
    condition      TEXT NOT NULL DEFAULT 'Near Mint',
    qty            INTEGER NOT NULL DEFAULT 1 CHECK (qty > 0),
    status         TEXT NOT NULL DEFAULT 'draft'
                   CHECK (status IN ('draft', 'listed', 'sold', 'ended')),
    price_gbp      DOUBLE PRECISION,
    cost_gbp       DOUBLE PRECISION,
    sold_price_gbp DOUBLE PRECISION,
    fees_gbp       DOUBLE PRECISION,
    postage_gbp    DOUBLE PRECISION,
    ebay_url       TEXT,
    note           TEXT NOT NULL DEFAULT '',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    listed_at      TIMESTAMPTZ,
    sold_at        TIMESTAMPTZ,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_listings_user ON listings (user_id, status);
